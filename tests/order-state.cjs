const assert=require('node:assert/strict');
const {applyVerifiedPayment,hasActiveLicense}=require('../backend/order-state.cjs');
const order={id:'ord-1',userId:'user-1',providerReference:'external-1',amountMinor:3990000,currency:'ARS',status:'pending'};
const payment={providerReference:'external-1',amountMinor:3990000,currency:'ARS',status:'approved',verifiedByServer:true};
assert.throws(()=>applyVerifiedPayment(order,{...payment,verifiedByServer:false}),/unverified_payment/);
assert.throws(()=>applyVerifiedPayment(order,{...payment,amountMinor:1}),/payment_mismatch/);
assert.throws(()=>applyVerifiedPayment(order,{...payment,currency:'USD'}),/payment_mismatch/);
assert.throws(()=>applyVerifiedPayment(order,{...payment,providerReference:'other'}),/payment_mismatch/);
assert.equal(hasActiveLicense(order),false);
const approved=applyVerifiedPayment(order,payment);
assert.equal(approved.status,'approved');
assert.equal(approved.changed,true);
assert.equal(hasActiveLicense(approved),true);
assert.equal(applyVerifiedPayment(approved,payment).changed,false,'Duplicate payment must be idempotent');
const refunded=applyVerifiedPayment(approved,{...payment,status:'refunded'});
assert.equal(hasActiveLicense(refunded),false);
assert.throws(()=>applyVerifiedPayment(refunded,payment),/invalid_transition/);
assert.throws(()=>applyVerifiedPayment(order,{...payment,status:'invalid'}),/invalid_status/);
console.log('Order state checks passed.');
